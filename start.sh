#!/usr/bin/env bash
# Launch a family watch in the Connect IQ simulator.
#
#   ./start.sh mom                          Mom's watch, local server
#   ./start.sh son                          Son's watch, local server
#   ./start.sh son http://<laptop-ip>:3000  Use another laptop's server
#
# The persona and server URL are built into the app, so each watch knows who
# it is and which server it's talking to. It shows the server on screen and
# prints it to the console.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
DEVICE="${DEVICE:-fenix7pro}"

usage() {
  cat <<'EOF'
Usage: ./start.sh <mom|son> [server-url]

  mom | son    Which persona this watch takes
  server-url   Server to use (default $FAMILY_API, else http://localhost:3000).
               A localhost server is started for you if it isn't running.

Env: DEVELOPER_KEY (defaults to VS Code's monkeyC.developerKeyPath), DEVICE (default fenix7pro)
EOF
}

die() { echo "error: $*" >&2; exit 1; }

case "${1:-}" in
  mom|mother) WHO=mom ;;
  son) WHO=son ;;
  -h|--help|help) usage; exit 0 ;;
  "") usage; exit 1 ;;
  *) echo "Unknown persona: $1" >&2; usage; exit 1 ;;
esac

SERVER="${2:-${FAMILY_API:-http://localhost:3000}}"
SERVER="${SERVER%/}"
[[ "$SERVER" =~ ^https?:// ]] || die "server URL must start with http:// or https:// (got '$SERVER')"

# ---- Connect IQ SDK + developer key ------------------------------------------
if command -v monkeyc >/dev/null 2>&1; then
  SDK_BIN="$(dirname "$(command -v monkeyc)")"
else
  SDK_DIR="$(ls -d "$HOME/Library/Application Support/Garmin/ConnectIQ/Sdks"/*/ 2>/dev/null | sort | tail -1 || true)"
  [[ -n "$SDK_DIR" ]] || die "Connect IQ SDK not found. Install it with the Connect IQ SDK Manager."
  SDK_BIN="${SDK_DIR%/}/bin"
fi

KEY="${DEVELOPER_KEY:-}"
VSCODE_SETTINGS="$HOME/Library/Application Support/Code/User/settings.json"
if [[ -z "$KEY" && -f "$VSCODE_SETTINGS" ]]; then
  KEY="$(grep -o '"monkeyC.developerKeyPath"[^,}]*' "$VSCODE_SETTINGS" | sed -E 's/.*:[[:space:]]*"(.*)"/\1/' || true)"
fi
[[ -n "$KEY" && -f "$KEY" ]] || die "developer key not found. Set DEVELOPER_KEY=/path/to/developer_key, or run 'Monkey C: Generate a Developer Key' in VS Code."

# ---- Server ------------------------------------------------------------------
# True only when our server answers, not just anything on that address.
up() { curl -fsS -m 3 "$SERVER/" 2>/dev/null | grep -q '"family-wellness"'; }

SERVER_PID=""
trap '[[ -n "$SERVER_PID" ]] && kill "$SERVER_PID" 2>/dev/null || true' EXIT

if up; then
  echo "Server: $SERVER"
elif [[ "$SERVER" =~ ^http://(localhost|127\.0\.0\.1):([0-9]+)$ ]]; then
  PORT="${BASH_REMATCH[2]}"
  echo "Server: starting $SERVER (log: bin/server.log; stops when this script exits)"
  mkdir -p "$ROOT/bin"
  [[ -d "$ROOT/server/node_modules" ]] || (cd "$ROOT/server" && npm install --no-audit --no-fund --silent)
  (cd "$ROOT/server" && PORT="$PORT" exec node src/index.js) > "$ROOT/bin/server.log" 2>&1 &
  SERVER_PID=$!
  for _ in $(seq 1 50); do up && break; sleep 0.2; done
  up || die "server didn't start; see bin/server.log"
else
  die "can't reach the server at $SERVER. Is it running on that laptop?"
fi

# ---- Build with this persona + server baked in (see Config.launchIdentity) ---
mkdir -p "$ROOT/bin/launch"
cat > "$ROOT/bin/launch/Launch.mc" <<EOF
// Generated by start.sh. Do not edit.
import Toybox.Lang;

module Config {
    function launchIdentity() as String? { return "$WHO"; }
    function launchServerUrl() as String? { return "$SERVER"; }
}
EOF
# Paths in this file are relative to bin/.
printf 'base.sourcePath = ../source;launch\nbase.excludeAnnotations = notLaunched\n' > "$ROOT/bin/launch.jungle"

PRG="$ROOT/bin/family-$WHO.prg"
rm -f "$PRG"
echo "Building $WHO's watch for $DEVICE..."
(cd "$ROOT" && "$SDK_BIN/monkeyc" -f "monkey.jungle;bin/launch.jungle" -d "$DEVICE" -o "$PRG" -y "$KEY") 2>&1 \
  | grep -v -E "No supported languages|launcher icon|container access" || true
[[ -f "$PRG" ]] || die "build failed"

# ---- Simulator (one per Mac) ---------------------------------------------------
if ! lsof -nP -iTCP:1234 -sTCP:LISTEN >/dev/null 2>&1; then
  echo "Starting the Connect IQ simulator..."
  "$SDK_BIN/connectiq"
  for _ in $(seq 1 60); do lsof -nP -iTCP:1234 -sTCP:LISTEN >/dev/null 2>&1 && break; sleep 0.5; done
fi
if [[ "$SERVER" == http://* ]]; then
  echo "Note: in the simulator, untick Settings > \"Use Device HTTPS Requirements\" (otherwise requests fail with -1001)."
fi

echo
echo "Running as $WHO -> $SERVER. Console output below; Ctrl-C to stop."
echo
"$SDK_BIN/monkeydo" "$PRG" "$DEVICE"
